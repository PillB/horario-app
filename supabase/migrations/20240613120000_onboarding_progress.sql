-- onboarding_progress
create table if not exists public.onboarding_progress (
  id bigint generated by default as identity primary key,
  account_id text not null,
  user_id text,
  workers_completed boolean not null default false,
  templates_completed boolean not null default false,
  forecast_completed boolean not null default false
);

alter table public.onboarding_progress
  add constraint onboarding_progress_account_user_key unique (account_id, user_id);

-- Enable RLS
alter table public.onboarding_progress enable row level security;

-- Read access for anon key (client-side reads)
create policy if not exists "Anon read onboarding progress" on public.onboarding_progress
  for select using (auth.role() = 'anon');

-- Allow anon upserts for onboarding flags
create policy if not exists "Anon upsert onboarding progress" on public.onboarding_progress
  for insert
  with check (auth.role() = 'anon');

create policy if not exists "Anon update onboarding progress" on public.onboarding_progress
  for update
  using (auth.role() = 'anon')
  with check (auth.role() = 'anon');

-- Service role can manage rows
create policy if not exists "Service role manages onboarding progress" on public.onboarding_progress
  for all
  using (auth.role() = 'service_role')
  with check (auth.role() = 'service_role');
