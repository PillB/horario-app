-- =============================================================================
-- Migration: forecast / demand-planning tables
-- Created:   2024-01-01
-- Depends:   (none — first migration)
--
-- Creates three tables that back the demand-forecasting flow:
--   shifts           – historical shift records (used as training data)
--   external_signals – demand boost/discount signals (events, promos, etc.)
--   demand_targets   – forecast output: required staffing per date+role
--
-- NOTE: CREATE POLICY does not support IF NOT EXISTS in PostgreSQL.
--       Each policy is preceded by DROP POLICY IF EXISTS to make this
--       migration safely re-runnable.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- shifts
-- ---------------------------------------------------------------------------
create table if not exists public.shifts (
  id        bigint generated by default as identity primary key,
  date      date          not null,
  role      text          not null,
  worker_id text          not null,
  hours     numeric(5,2)  not null check (hours >= 0)
);

create index if not exists shifts_date_role_idx
  on public.shifts (date, role);

alter table public.shifts enable row level security;

drop policy if exists "Anon read shifts" on public.shifts;
create policy "Anon read shifts"
  on public.shifts for select
  using (auth.role() = 'anon');

drop policy if exists "Service role writes shifts" on public.shifts;
create policy "Service role writes shifts"
  on public.shifts for all
  using (auth.role() = 'service_role')
  with check (auth.role() = 'service_role');

-- ---------------------------------------------------------------------------
-- external_signals
-- ---------------------------------------------------------------------------
create table if not exists public.external_signals (
  id          bigint generated by default as identity primary key,
  date        date           not null,
  role        text           not null,
  signal_type text           not null,
  weight      numeric(10,4)  not null
