-- ---------------------------------------------------------------------------
-- demand_targets
-- ---------------------------------------------------------------------------
create table if not exists public.demand_targets (
  id          bigint generated by default as identity primary key,
  date        date           not null,
  role        text           not null,
  required    numeric(10,2)  not null,
  notes       text,
  confidence  numeric(5,4),
  lower_bound numeric(10,2),
  upper_bound numeric(10,2),
  source      text
);

-- Unique on (date, role) so the proxy can upsert with onConflict: 'date,role'.
-- Wrapped in a DO block so re-running the migration does not fail if the
-- constraint already exists (ALTER TABLE ADD CONSTRAINT has no IF NOT EXISTS).
do $$ begin
  alter table public.demand_targets
    add constraint demand_targets_date_role_key unique (date, role);
exception when duplicate_object then
  null; -- constraint already exists, nothing to do
end $$;

alter table public.demand_targets enable row level security;

drop policy if exists "Anon read demand targets" on public.demand_targets;
create policy "Anon read demand targets"
  on public.demand_targets for select
  using (auth.role() = 'anon');

drop policy if exists "Service role writes demand targets" on public.demand_targets;
create policy "Service role writes demand targets"
  on public.demand_targets for all
  using (auth.role() = 'service_role')
  with check (auth.role() = 'service_role');
